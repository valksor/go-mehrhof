func TestParseOwnerRepo(t *testing.T) {
	tests := []struct {
		in        string
		wantOwner string
		wantRepo  string
	}{
		{"owner/repo#123", "owner", "repo"},
		{"acme/widgets#1", "acme", "widgets"},
		{"no-hash", "", ""},
		{"onlyowner#5", "", ""},
		{"a/b/c#5", "a", "b/c"},
		{"", "", ""},
	}
	for _, tt := range tests {
		t.Run(tt.in, func(t *testing.T) {
			owner, repo := parseOwnerRepo(tt.in)
			if owner != tt.wantOwner || repo != tt.wantRepo {
				t.Errorf("parseOwnerRepo(%q) = (%q,%q), want (%q,%q)", tt.in, owner, repo, tt.wantOwner, tt.wantRepo)
			}
		})
	}
}

func TestFillPRTemplate(t *testing.T) {
	template := strings.Join([]string{
		"## Summary",
		"",
		"## How to test",
		"",
		"## Related issue",
		"",
	}, "\n")

	out := fillPRTemplate(template, "My change", 3, "https://example.com/issue/1")

	if !strings.Contains(out, "My change") {
		t.Errorf("summary not filled: %q", out)
	}
	if !strings.Contains(out, "3 checkpoint(s) reviewed") {
		t.Errorf("test section not filled: %q", out)
	}
	if !strings.Contains(out, "https://example.com/issue/1") {
		t.Errorf("related section not filled: %q", out)
	}
}

