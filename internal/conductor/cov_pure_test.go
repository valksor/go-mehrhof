func TestValidatePRSections(t *testing.T) {
	body := strings.Join([]string{
		"## Summary",
		"Real content here",
		"## Testing",
		"<!-- placeholder -->",
		"## Empty",
		"",
	}, "\n")

	missing := validatePRSections(body, []string{"Summary", "Testing", "Empty", "Absent"})

	has := func(s string) bool {
		return slices.Contains(missing, s)
	}
	if has("Summary") {
		t.Error("Summary has content; should not be reported missing")
	}
	if !has("Testing") {
		t.Error("Testing only has placeholder; should be reported missing")
	}
	if !has("Empty") {
		t.Error("Empty section should be reported missing")
	}
	if !has("Absent") {
		t.Error("Absent header should be reported missing")
	}
}

func TestWorkUnitTaskStateRoundTrip(t *testing.T) {
	created := time.Now().Add(-time.Hour).Round(time.Second)
	updated := time.Now().Round(time.Second)
	approvedAt := time.Now().Add(-30 * time.Minute).Round(time.Second)

	wu := &WorkUnit{
		ID:             "task-1",
		ExternalID:     "ext-1",
		Title:          "Title",
		Description:    "Desc",
		Branch:         "feature/x",
		WorktreePath:   "/tmp/wt",
		Specifications: []string{"spec1.md", "spec2.md"},
		Checkpoints:    []string{"sha1", "sha2"},
		RedoStack:      []string{"sha3"},
		Jobs:           []string{"job1"},
		Metadata:       map[string]string{"k": "v"},
		Tags:           []string{"urgent"},
		Priority:       5,
		HasImplemented: true,
		TaskTraceID:    "trace-1",
		CreatedAt:      created,
		UpdatedAt:      updated,
		Source:         &Source{Provider: "github", Reference: "owner/repo#1", URL: "https://x", Content: "content"},
		Approvals: map[string]ApprovalRecord{
			"submit": {ApprovedBy: "alice", ApprovedAt: approvedAt},
		},
		Hierarchy: &HierarchyContext{
			Parent: &TaskSummary{ID: "p1", Title: "Parent", Description: "pd", URL: "pu", Status: "open"},
			Siblings: []TaskSummary{
				{ID: "s1", Title: "Sib", Description: "sd", URL: "su", Status: "done"},
			},
		},
		CheckpointMeta: map[string]CheckpointMeta{
			"sha1": {Message: "first", State: "planned", CreatedAt: created},
		},
	}
	history := []HistoryEntry{
		{From: StateNone, To: StateLoaded, Event: EventStart, Timestamp: created},
		{From: StateLoaded, To: StatePlanning, Event: EventPlan, Timestamp: updated},
	}

	ts := workUnitToTaskState(StatePlanned, wu, history)
	if ts.State != string(StatePlanned) {
		t.Errorf("State = %q", ts.State)
	}
	if ts.ID != "task-1" || ts.ExternalID != "ext-1" {
		t.Errorf("ids not preserved: %+v", ts)
	}
	if ts.Source == nil || ts.Source.Provider != "github" {
		t.Error("source not converted")
	}
	if ts.Hierarchy == nil || ts.Hierarchy.Parent == nil || ts.Hierarchy.Parent.ID != "p1" {
		t.Error("hierarchy parent not converted")
	}
	if len(ts.Hierarchy.Siblings) != 1 {
		t.Error("hierarchy siblings not converted")
	}
	if len(ts.History) != 2 {
		t.Errorf("history len = %d", len(ts.History))
	}
	if ts.Approvals["submit"].ApprovedBy != "alice" {
		t.Error("approval not converted")
	}
	if ts.CheckpointMeta["sha1"].Message != "first" {
		t.Error("checkpoint meta not converted")
	}

	// Round-trip back
	state, wu2, history2 := taskStateToWorkUnit(ts)
	if state != StatePlanned {
		t.Errorf("round-trip state = %q", state)
	}
	if wu2.ID != wu.ID || wu2.Title != wu.Title || wu2.Branch != wu.Branch {
		t.Errorf("round-trip workunit mismatch: %+v", wu2)
	}
	if !wu2.HasImplemented {
		t.Error("HasImplemented lost in round-trip")
	}
	if wu2.Source == nil || wu2.Source.Reference != "owner/repo#1" {
		t.Error("source lost in round-trip")
	}
	if wu2.Hierarchy == nil || wu2.Hierarchy.Parent == nil || wu2.Hierarchy.Parent.ID != "p1" {
		t.Error("hierarchy lost in round-trip")
	}
	if wu2.Approvals["submit"].ApprovedBy != "alice" {
		t.Error("approval lost in round-trip")
	}
	if wu2.CheckpointMeta["sha1"].State != "planned" {
		t.Error("checkpoint meta lost in round-trip")
	}
	if len(history2) != 2 || history2[0].Event != EventStart {
		t.Errorf("history lost in round-trip: %+v", history2)
	}
}

