func TestIsActivePhaseState(t *testing.T) {
	active := []State{StatePlanning, StateImplementing, StateSimplifying, StateOptimizing, StateReviewing}
	for _, s := range active {
		if !isActivePhaseState(s) {
			t.Errorf("isActivePhaseState(%s) = false, want true", s)
		}
	}
	inactive := []State{StateNone, StateLoaded, StatePlanned, StateImplemented, StateSubmitted, StateFailed, StateWaiting, StatePaused, State("garbage")}
	for _, s := range inactive {
		if isActivePhaseState(s) {
			t.Errorf("isActivePhaseState(%s) = true, want false", s)
		}
	}
}
