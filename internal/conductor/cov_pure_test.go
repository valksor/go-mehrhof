func TestBuildPRDescription_FullBody(t *testing.T) {
	fileStatuses := []git.FileStatus{
		{Path: "a.go", Status: "added"},
		{Path: "b.go", Status: "deleted"},
		{Path: "c.go", Status: "modified"},
		{Path: "d.go", Status: "renamed"},
		{Path: "e.go", Status: "weird"},
	}
	prc := &prContext{
		SpecContent:   "the spec content",
		ReviewSummary: "Quality gate: passed",
	}
	body := buildPRDescription("A great feature", 1, 2, "1 file changed", fileStatuses, []settings.PRSection{
		{Title: "Notes", Content: "extra"},
	}, prc)

	for _, want := range []string{
		"## Summary", "A great feature",
		"## Changes", "`+` a.go", "`-` b.go", "`~` c.go", "`>` d.go", "`?` e.go",
		"Diff stats", "## Specification", "the spec content",
		"## Review", "Quality gate: passed",
		"## Checkpoints", "2 checkpoint(s)",
		"## Notes", "extra",
		"Generated by",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("body missing %q\n---\n%s", want, body)
		}
	}
}

